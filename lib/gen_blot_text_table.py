#!/usr/bin/env python3
# blot: generate lib/blot_text_table.h, the display widths blot uses when
# the locale can't measure a character (the C locale).
#
#   python3 lib/gen_blot_text_table.py > lib/blot_text_table.h
#
# The widths are glibc's wcwidth() in the C.UTF-8 locale, so the table
# agrees with a UTF-8 locale by construction: the ranges of characters
# that take no column (combining marks, format characters, conjoining
# Hangul vowels and finals) and those that take two (East Asian Wide and
# Fullwidth, emoji).  Everything else takes one.  A range runs on across
# code points glibc doesn't know (wcwidth -1), which keeps the table small.
import ctypes

LC_ALL = 6

libc = ctypes.CDLL("libc.so.6")
libc.setlocale.restype = ctypes.c_char_p
libc.setlocale.argtypes = [ctypes.c_int, ctypes.c_char_p]
libc.gnu_get_libc_version.restype = ctypes.c_char_p
if not libc.setlocale(LC_ALL, b"C.UTF-8"):
    raise SystemExit("the C.UTF-8 locale is missing")
wcwidth = libc.wcwidth
wcwidth.argtypes = [ctypes.c_uint32]
wcwidth.restype = ctypes.c_int


def width(c):
    if 0xD800 <= c <= 0xDFFF:
        return -1
    return wcwidth(c)


def ranges(target):
    out = []
    cur = None
    for c in range(0xA0, 0x110000):
        w = width(c)
        if w == target:
            if cur:
                cur[1] = c
            else:
                cur = [c, c]
                out.append(cur)
        elif w != -1:
            cur = None
    return out


def emit(name, rs):
    print("static const struct blot_text_range %s[%d] = {" % (name, len(rs)))
    for i in range(0, len(rs), 4):
        print("\t" + " ".join("{ 0x%05X, 0x%05X }," % (a, b) for a, b in rs[i:i + 4]))
    print("};")


print("/* blot: display widths for the C locale, generated by")
print(" * lib/gen_blot_text_table.py from glibc %s's C.UTF-8 wcwidth(): do"
      % libc.gnu_get_libc_version().decode())
print(" * not edit */")
print("/* vim: set noet sw=8 ts=8 tw=120: */")
print("#pragma once")
print()
print("/* characters that take no column */")
emit("blot_text_zero", ranges(0))
print()
print("/* characters that take two columns */")
emit("blot_text_wide", ranges(2))
